let LANG = localStorage.getItem('compass_lang') || 'fr';

function setLang(l) {
  LANG = l;
  localStorage.setItem('compass_lang', l);
  // Update toggle buttons
  document.querySelectorAll('.lang-btn-fr,.lang-btn-en').forEach(b => {
    b.classList.toggle('btn-p', (b.classList.contains('lang-btn-fr') && l==='fr') || (b.classList.contains('lang-btn-en') && l==='en'));
  });
  // Re-render current screen if render exists
  if (typeof render === 'function' && typeof S !== 'undefined') render(S.step, 0);
  // Toggle server-side bilingual spans
  document.querySelectorAll('.i18n-fr,.i18n-en').forEach(el => {
    if (el.classList.contains('i18n-fr')) el.style.display = LANG === 'fr' ? '' : 'none';
    if (el.classList.contains('i18n-en')) el.style.display = LANG === 'en' ? '' : 'none';
  });
}

function t(key) {
  const entry = I18N[key];
  if (!entry) return key;
  return entry[LANG] || entry.fr || key;
}

